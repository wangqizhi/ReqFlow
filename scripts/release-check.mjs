import { build } from 'esbuild';
import { mkdtemp, readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const dir = await mkdtemp(path.join(os.tmpdir(), 'reqflow-1.1-'));
try {
  const entry = path.join(dir, 'entry.ts');
  await writeFile(entry, ['src/core/domain.ts','src/core/service.ts','src/core/storage.ts','src/core/remote.ts','src/main/remote.ts'].map((f) => `export * from ${JSON.stringify(path.resolve(f))};`).join('\n'));
  const out = path.join(dir, 'bundle.mjs');
  await build({ entryPoints: [entry], outfile: out, bundle: true, format: 'esm', platform: 'node', logLevel: 'silent' });
  const { WorkspaceStore, WorkspaceService, BackupManager, emptyRemote, validateRemote } = await import(pathToFileURL(out));
  const dataDir = path.join(dir, 'data');
  const svc = new WorkspaceService(new WorkspaceStore(path.join(dataDir, 'workspace.json')));
  let r = await svc.get(); const project = r.state.projects[0].id;
  const act = async (action) => { r = await svc.mutate({ project, ...action }, null); return r.state.projects[0]; };
  await act({ op: 'item', body: '默认交付' });
  await act({ op: 'item', body: '定制交付', deliveryGuidance: '独立定制文案' });
  let p = await act({ op: 'generate', ids: r.state.projects[0].items.map((i) => i.id) });
  const initial = structuredClone(p.batches[0]);
  await act({ op: 'submit', batch: initial.id });
  p = await act({ op: 'guidance', text: p.guidance, deliveryGuidance: '新交付内容，生成安装包' });
  assert.equal(p.items[0].deliveryGuidance, '新交付内容，生成安装包');
  assert.equal(p.items[1].deliveryGuidance, '独立定制文案');
  assert.equal(p.batches[0].text, initial.text, '历史批次保持原文');
  p = await act({ op: 'generate', ids: [p.items[0].id] });
  assert.match(p.batches[0].text, /新交付内容，生成安装包/);
  assert.notEqual(p.batches[0].hash, initial.hash);
  await act({ op: 'submit', batch: p.batches[0].id });
  p = await act({ op: 'generate', ids: p.items.map((i) => i.id) });
  assert.match(p.batches[0].text, /新交付内容，生成安装包/);
  assert.match(p.batches[0].text, /独立定制文案/);
  p = await act({ op: 'projectDescription', description: '可编辑的项目背景' });
  p = await act({ op: 'generate', ids: p.items.map((i) => i.id) });
  assert.match(p.batches[0].text, /可编辑的项目背景/);
  p = await act({ op: 'projectRemote', remote: { ...emptyRemote, provider: 'gitlab', url: 'git@gitlab.example.com:team/repo.git', sshKeyPath: 'C:/keys/id_ed25519' } });
  assert.equal(p.remote.provider, 'gitlab');
  for (const url of ['file:///test', '-bad', 'https://user:token@github.com/a/b', 'ext::command']) assert.throws(() => validateRemote({ ...emptyRemote, url }));
  assert.throws(() => validateRemote({ ...emptyRemote, branch: 'bad..branch' }));
  const bare = path.join(dir, 'remote.git');
  execFileSync('git', ['init', '--bare', bare], { windowsHide: true, stdio: 'pipe' });
  // 仅本测试进程的 Git 环境将虚拟 HTTPS 地址映射到临时 bare 仓库。
  process.env.GIT_CONFIG_COUNT = '1';
  process.env.GIT_CONFIG_KEY_0 = `url.${bare.replaceAll('\\','/')}.insteadOf`;
  process.env.GIT_CONFIG_VALUE_0 = 'https://backup.example/workspace.git';
  await writeFile(path.join(dataDir, 'ai-settings.json'), JSON.stringify({ provider: 'Test', url: 'https://api.example/v1', encryptedKey: 'DO_NOT_UPLOAD_SECRET' }));
  const manager = new BackupManager(dataDir);
  assert.equal((await manager.load()).autoSync, true);
  let scheduled;
  const originalSetInterval = globalThis.setInterval;
  globalThis.setInterval = (callback, ms) => { assert.equal(ms, 60000); scheduled = callback; return { unref() {} }; };
  await manager.save({ ...emptyRemote, url: 'https://backup.example/workspace.git', autoSync: true });
  globalThis.setInterval = originalSetInterval;
  assert.equal(typeof scheduled, 'function', '默认自动同步每60秒运行');
  await manager.save({ ...emptyRemote, url: 'https://backup.example/workspace.git', autoSync: false });
  const sync = manager.sync();
  await assert.rejects(manager.sync(), /正在同步/);
  await sync;
  assert.ok(manager.status.lastSuccess);
  let backup = JSON.parse(execFileSync('git', ['--git-dir', bare, 'show', 'main:reqflow-backup.json'], { encoding: 'utf8', windowsHide: true }));
  assert.equal(backup.workspace.projects[0].description, '可编辑的项目背景');
  assert.equal(backup.settings.ai, undefined, '全部 AI 配置仅本机保存');
  assert.ok(!JSON.stringify(backup).includes('https://api.example/v1'));
  assert.ok(!JSON.stringify(backup).includes('DO_NOT_UPLOAD_SECRET'));
  const count = () => Number(execFileSync('git', ['--git-dir', bare, 'rev-list', '--count', 'main'], { encoding: 'utf8', windowsHide: true }));
  assert.equal(count(), 1);
  await manager.sync(); assert.equal(count(), 1, '数据未变不产生commit');
  await act({ op: 'item', body: 'CLI 更新的新需求' });
  // 推送被拒后，本地commit保留；下次没有新数据也会重试push。
  const hook = path.join(bare, 'hooks', 'pre-receive');
  await writeFile(hook, '#!/bin/sh\nexit 1\n');
  await assert.rejects(manager.sync()); assert.ok(manager.status.error); assert.equal(count(), 1);
  await rm(hook);
  await manager.sync(); assert.equal(count(), 2); assert.equal(manager.status.error, undefined);
  backup = JSON.parse(execFileSync('git', ['--git-dir', bare, 'show', 'main:reqflow-backup.json'], { encoding: 'utf8', windowsHide: true }));
  assert.equal(backup.workspace.projects[0].items.length, 3);
  const restored = new WorkspaceService(new WorkspaceStore(path.join(dir, 'restored', 'workspace.json')));
  await restored.importWorkspace(backup, true);
  assert.equal((await restored.get()).state.projects[0].items.length, 3);
  // 远程新增提交必须先快进，再叠加备份。
  const clone = path.join(dir, 'other');
  execFileSync('git', ['clone', '--branch', 'main', bare, clone], { windowsHide: true, stdio: 'pipe' });
  await writeFile(path.join(clone, 'readme.txt'), 'remote change');
  execFileSync('git', ['-C', clone, 'add', 'readme.txt'], { windowsHide: true });
  execFileSync('git', ['-C', clone, '-c', 'user.name=Test', '-c', 'user.email=test@example.com', 'commit', '-m', 'remote change'], { windowsHide: true, stdio: 'pipe' });
  execFileSync('git', ['-C', clone, 'push', 'origin', 'main'], { windowsHide: true, stdio: 'pipe' });
  await act({ op: 'item', body: '远程更新后继续备份' });
  await manager.sync(); assert.equal(count(), 4);
  console.log('PASS: 项目背景/仓库配置、单条与全部Prompt更新、独立交付保留、60秒调度、真实Git备份/去重/失败重试/远程快进/恢复/密钥排除');
} finally {
  await rm(dir, { recursive: true, force: true });
}
