import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

export async function buildPluginBundles(root) {
  const bundles = {};
  for (const [host, name, manifest] of [
    ['codex', 'reqflow-agent', 'plugin.json'],
    ['zcode', 'reqflow-agent-zcode', '.zcode-plugin/plugin.json'],
    ['pi', 'reqflow-agent-pi', 'package.json'],
  ]) {
    const directory = path.join(root, 'plugins', name);
    const meta = JSON.parse(await readFile(path.join(directory, manifest), 'utf8'));
    const files = {};
    async function visit(relative = '') {
      for (const item of (await readdir(path.join(directory, relative), { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
        const file = relative ? `${relative}/${item.name}` : item.name;
        if (item.isDirectory()) await visit(file);
        else if (item.isFile()) files[file] = await readFile(path.join(directory, file), 'utf8');
        else throw Error(`Unexpected plugin asset: ${file}`);
      }
    }
    await visit();
    const canonical = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
    bundles[host] = { name, version: meta.version, files: canonical, sha256: createHash('sha256').update(JSON.stringify(canonical)).digest('hex') };
  }
  await writeFile(path.join(root, 'src/mygo/backendgo/plugins_generated.go'),
    '// Code generated by scripts/build-plugin-bundles.mjs. DO NOT EDIT.\npackage backendgo\n\nfunc init() { pluginBundlesJSON = ' + JSON.stringify(JSON.stringify(bundles)) + ' }\n');
}
